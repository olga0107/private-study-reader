begin;

-- Auth accounts are created by an administrator. Public sign-up stays disabled.
-- Checking the account also rejects a deleted/banned user with an unexpired JWT.
create or replace function public.is_reader()
returns boolean language sql stable security definer
set search_path = ''
as $$
  select exists (
    select 1 from auth.users
    where id = (select auth.uid())
      and deleted_at is null
      and (banned_until is null or banned_until <= now())
  );
$$;
revoke all on function public.is_reader() from public, anon;
grant execute on function public.is_reader() to authenticated;

insert into storage.buckets (id, name, public)
values ('site-content', 'site-content', false)
on conflict (id) do update set public = false;

drop policy if exists site_content_readers on storage.objects;
create policy site_content_readers on storage.objects
for select to authenticated
using (bucket_id = 'site-content' and (select public.is_reader()));

create table if not exists public.annotations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  page_path text not null,
  kind text not null check (kind in ('marks', 'ink')),
  payload jsonb not null,
  updated_at timestamptz not null default now(),
  unique (user_id, page_path, kind)
);
alter table public.annotations add column if not exists revision bigint not null default 1;
alter table public.annotations enable row level security;

drop policy if exists annotations_select_own on public.annotations;
drop policy if exists annotations_insert_own on public.annotations;
drop policy if exists annotations_update_own on public.annotations;
drop policy if exists annotations_delete_own on public.annotations;
create policy annotations_select_own on public.annotations
for select to authenticated
using (user_id = (select auth.uid()) and (select public.is_reader()));

-- The only write entrypoint checks the revision atomically. A stale/offline
-- client gets a conflict instead of overwriting newer notes on another device.
revoke all on public.annotations from anon, authenticated;
grant select on public.annotations to authenticated;
create or replace function public.save_annotation(
  p_page_path text, p_kind text, p_payload jsonb, p_expected_revision bigint
) returns jsonb language plpgsql security definer
set search_path = ''
as $$
declare
  owner_id uuid := auth.uid();
  saved public.annotations;
begin
  if owner_id is null or not public.is_reader() then
    raise exception 'Not authorized' using errcode = '42501';
  end if;
  if p_page_path is null or p_page_path !~ '^/(notes|foundations)/[a-z0-9-]+$'
     or p_kind is null or p_kind not in ('marks', 'ink')
     or p_payload is null or jsonb_typeof(p_payload) not in ('object', 'array')
     or p_expected_revision is null or p_expected_revision < 0
     or octet_length(p_payload::text) > 10000000 then
    raise exception 'Invalid annotation' using errcode = '22023';
  end if;
  if p_expected_revision = 0 then
    insert into public.annotations (user_id, page_path, kind, payload, revision)
    values (owner_id, p_page_path, p_kind, p_payload, 1)
    on conflict (user_id, page_path, kind) do nothing
    returning * into saved;
  else
    update public.annotations
    set payload = p_payload, revision = revision + 1, updated_at = now()
    where user_id = owner_id and page_path = p_page_path and kind = p_kind
      and revision = p_expected_revision
    returning * into saved;
  end if;
  if saved.id is not null then
    return jsonb_build_object('ok', true, 'row', to_jsonb(saved));
  end if;
  select * into saved from public.annotations
  where user_id = owner_id and page_path = p_page_path and kind = p_kind;
  return jsonb_build_object('ok', false, 'row', to_jsonb(saved));
end;
$$;
revoke all on function public.save_annotation(text, text, jsonb, bigint) from public, anon;
grant execute on function public.save_annotation(text, text, jsonb, bigint) to authenticated;
commit;
